const {contextBridge,ipcRenderer}=require('electron');
const invoke=async(channel,...args)=>{const r=await ipcRenderer.invoke(channel,...args);if(!r.ok)throw new Error(r.error);return r.value;};
contextBridge.exposeInMainWorld('editor',{
  musicAdopt:id=>invoke('editor:music-adopt',id),
  musicCancel:()=>invoke('editor:music-cancel'),
  musicSearch:(query,kind)=>invoke('editor:music-search',query,kind),
  musicReplay:id=>invoke('editor:music-replay',id),
  musicPrepare:id=>invoke('editor:music-prepare',id),
  recordingArm:()=>invoke('editor:recording-arm'),
  recordingDisarm:()=>invoke('editor:recording-disarm'),
  recordingSave:(bytes,mime)=>invoke('editor:recording-save',bytes,mime),
  importMedia:kind=>invoke('editor:import',kind),
  relinkFolder:project=>invoke('editor:relink-folder',project),
  relink:assetId=>invoke('editor:relink',assetId),
  saveProject:(project,history,mode)=>invoke('editor:save',project,history,mode),
  onSaveProject:listener=>{const handler=(_event,mode)=>listener(mode);ipcRenderer.on('editor:save-project',handler);return ()=>ipcRenderer.removeListener('editor:save-project',handler);},
  updateStatus:()=>invoke('editor:update-status'),
  checkUpdate:()=>invoke('editor:update-check'),
  installUpdate:()=>invoke('editor:update-install'),
  onUpdate:listener=>{const handler=(_event,state)=>listener(state);ipcRenderer.on('editor:update',handler);return ()=>ipcRenderer.removeListener('editor:update',handler);},
  ready:()=>invoke('editor:ready'),
  openProject:token=>invoke('editor:open',token),
  mediaState:id=>invoke('editor:media-state',id),
  cancelMediaValidation:id=>invoke('editor:cancel-media',id),
  clearPreview:()=>invoke('editor:clear-preview'),
  reviewSpeech:project=>invoke('editor:speech-review',project),
  preparePreview:project=>invoke('editor:prepare-preview',project),
  previewTiming:elapsedMs=>invoke('editor:preview-timing',elapsedMs),
  diagnosticStatus:()=>invoke('editor:diagnostic-status'),
  exportDiagnostics:()=>invoke('editor:diagnostic-export'),
  reportDiagnosticError:error=>invoke('editor:diagnostic-error',error),
  copyPerformanceDiagnostics:()=>invoke('editor:performance-diagnostics'),
  onMediaState:listener=>{const handler=(_event,state)=>listener(state);ipcRenderer.on('editor:media-state',handler);return ()=>ipcRenderer.removeListener('editor:media-state',handler);},
  onOpenProject:listener=>{const handler=(_event,token)=>listener(token);ipcRenderer.on('editor:open-project',handler);return ()=>ipcRenderer.removeListener('editor:open-project',handler);},
  exportProject:(project,height,range=null)=>invoke('editor:export',project,height,range),
  exportBatch:(project,height,jobs,runId)=>invoke('editor:export-batch',project,height,jobs,runId),
  revealExport:file=>invoke('editor:reveal-export',file),
  status:()=>invoke('editor:status'),
  speechModel:()=>invoke('editor:speech-model'),
  searchModel:()=>invoke('editor:search-model'),
  installSearchModel:()=>invoke('editor:search-model-install'),
  onSearchModel:listener=>{const handler=(_event,progress)=>listener(progress);ipcRenderer.on('editor:search-model',handler);return ()=>ipcRenderer.removeListener('editor:search-model',handler);},
  installSpeechModel:()=>invoke('editor:speech-model-install'),
  onSpeechModel:listener=>{const handler=(_event,progress)=>listener(progress);ipcRenderer.on('editor:speech-model',handler);return ()=>ipcRenderer.removeListener('editor:speech-model',handler);},
  login:()=>invoke('editor:login'),
  analyze:(project,prompt,step,clipId,engine,shareEvidence,stage=null)=>invoke('editor:analyze',project,prompt,step,clipId,engine,shareEvidence,stage),
  apiStatus:()=>invoke('editor:api-status'),
  apiSave:key=>invoke('editor:api-save',key),
  apiClipboard:()=>invoke('editor:api-clipboard'),
  apiRemove:()=>invoke('editor:api-remove'),
  captionEstimate:project=>invoke('editor:caption-estimate',project),
  transcribe:project=>invoke('editor:transcribe',project),
  transcribeLocal:project=>invoke('editor:transcribe-local',project),
  importSubtitles:()=>invoke('editor:subtitle-import'),
  exportSubtitles:(project,format)=>invoke('editor:subtitle-export',project,format),
  cancel:()=>invoke('editor:cancel'),
  setBusy:value=>invoke('editor:busy',value),
  setDirty:dirty=>invoke('editor:dirty',dirty),
  onProgress:listener=>{const handler=(_,p)=>listener(p);ipcRenderer.on('editor:progress',handler);return ()=>ipcRenderer.removeListener('editor:progress',handler);}
});
