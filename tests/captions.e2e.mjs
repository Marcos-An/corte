import assert from 'node:assert/strict';
import path from 'node:path';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { createRequire } from 'node:module';
import { binaries, run, probe } from '../desktop/media.mjs';
const require=createRequire(import.meta.url);
const {_electron:electron}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const dir=await mkdtemp(path.join(tmpdir(),'corte-e2e-'));
const root=path.resolve(import.meta.dirname,'..');
await run(binaries().ffmpeg,['-hide_banner','-loglevel','error','-y','-f','lavfi','-i','testsrc2=size=640x360:rate=30','-f','lavfi','-i','sine=frequency=440:sample_rate=48000','-t','4','-c:v','libx264','-pix_fmt','yuv420p','-c:a','aac',path.join(dir,'source.mp4')]);
let app;
try {
 app=await electron.launch({executablePath:require('electron'),args:[root,`--user-data-dir=${path.join(dir,'appdata')}`],env:{...process.env,ELECTRON_RUN_AS_NODE:''}});
 const page=await app.firstWindow();await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setBounds({width:1200,height:800}));const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.getByRole('button',{name:'Importar vídeos',exact:true}).waitFor({timeout:15000});
 await app.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});},path.join(dir,'source.mp4'));
 await page.getByRole('button',{name:'Importar vídeos',exact:true}).click();
 await page.waitForFunction(()=>document.querySelectorAll('.timeline-clip').length===1);
 assert.equal(await page.locator('.timeline-clip').count(),1);
 await app.evaluate(({ipcMain})=>{ipcMain.removeHandler('editor:transcribe');ipcMain.handle('editor:transcribe',(_,p)=>({ok:true,value:[{assetId:p.assets[0].id,words:[{start:0,end:1,text:'Olá'},{start:1,end:2,text:'mundo'}]}]}));});
 await page.getByRole('button',{name:'Legendas',exact:true}).click();
 await page.getByRole('button',{name:'Gerar legendas locais'}).click();
 await page.getByLabel('Palavra 1',{exact:true}).fill('Oi');await page.getByLabel('Palavra 1',{exact:true}).dispatchEvent('change');
 await app.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},path.join(dir,'caption.corte'));
 await page.getByRole('button',{name:'Salvar projeto',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#save-state').textContent.includes('Salvo'));
 const saved=JSON.parse(await readFile(path.join(dir,'caption.corte'),'utf8'));assert.equal(saved.project.transcripts[0].words[0].text,'Oi');
 assert.deepEqual(errors,[]);console.log('PASS captions UI generation and editable words');
}finally{if(app){await app.evaluate(({dialog})=>{dialog.showMessageBoxSync=()=>1;});await app.close();}await rm(dir,{recursive:true,force:true});}
